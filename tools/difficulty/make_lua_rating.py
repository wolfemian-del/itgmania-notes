#!/usr/bin/env python3
"""Generate a Lua rating script from the model.json written by
fit_difficulty_model.py (v2).

Usage:
    python make_lua_rating.py model.json DifficultyModel.lua

The model must have been fitted with --no-tech (the Lua port does not
compute tech counts). Coefficients and calibration knots are copied from
model.json at full precision, so nothing is typed by hand.

The generated file defines one global table, DifficultyModel, with:
    DifficultyModel.Rating(steps [, pn [, opts]]) -> rating, raw, calibrated
        rating      integer 1..19, or nil if the chart cannot be rated
        raw         linear model value (before calibration)
        calibrated  value after the monotone calibration map (before rounding)
        on nil, the 2nd return value is a reason string instead
    DifficultyModel.Features(steps [, pn]) -> table of feature values

Put the file in a theme's Scripts folder (or the Scripts folder of the
install). Lua 5.1 compatible (the engine's version). Rating 20 is never
produced: the training corpus has no label above 19.
"""
import json
import sys
from pathlib import Path

HEADER = """-- DifficultyModel.lua  (generated by make_lua_rating.py; do not edit by hand)
-- Steps type trained on: {steps_type}.  Charts: {n}.  Cross-validated
-- (song-grouped, calibrated): MAE {mae}, within one foot {w1}%.
-- Chart difficulty estimated from cached chart data only. Rating 20 is never
-- produced (no training label above 19). Not validated on non-DDR charts.
"""

BODY = r"""
DifficultyModel = {}

local B0 = %(b0)r
local COEF = {
%(coef)s}
local KX = {%(kx)s}
local KY = {%(ky)s}
local MAX_RATING = 19
local STEPS_TYPE = %(st)r

-- max mean NPS over any run of w consecutive measures (0 if fewer measures)
local function Sustained(nps, w)
	local n = #nps
	if n < w then return 0 end
	local cur = 0
	for i = 1, w do cur = cur + nps[i] end
	local best = cur
	for i = w + 1, n do
		cur = cur + nps[i] - nps[i - w]
		if cur > best then best = cur end
	end
	return best / w
end

local function Interp(x, xs, ys)
	local n = #xs
	if x <= xs[1] then return ys[1] end
	if x >= xs[n] then return ys[n] end
	for i = 2, n do
		if x <= xs[i] then
			local t = (x - xs[i - 1]) / (xs[i] - xs[i - 1])
			return ys[i - 1] + t * (ys[i] - ys[i - 1])
		end
	end
	return ys[n]
end

-- Returns a table of features, or nil plus a reason.
function DifficultyModel.Features(steps, pn)
	pn = pn or PLAYER_1
	local nps = steps:GetNpsPerMeasure(pn)
	local notes = steps:GetNotesPerMeasure(pn)
	if not nps or #nps == 0 or not notes or #notes == 0 then
		return nil, "no measure data"
	end
	local rv = steps:GetRadarValues(pn)
	local function R(name) return rv:GetValue("RadarCategory_" .. name) end
	local radar = {}
	for _, nm in ipairs({"Stream", "Voltage", "Air", "Freeze", "Chaos",
			"Mines", "Holds", "Rolls", "Jumps"}) do
		radar[nm] = R(nm)
		if radar[nm] == nil or radar[nm] < 0 then
			return nil, "radar value unknown: " .. nm
		end
	end

	local nz, rows = {}, 0
	for _, v in ipairs(nps) do if v > 0 then nz[#nz + 1] = v end end
	for _, v in ipairs(notes) do rows = rows + v end
	local f = {}
	f.radar_Stream = radar.Stream
	f.radar_Voltage = radar.Voltage
	f.radar_Air = radar.Air
	f.radar_Freeze = radar.Freeze
	f.radar_Chaos = radar.Chaos
	f.peak_nps = steps:GetPeakNps(pn)
	local sum = 0
	for _, v in ipairs(nz) do sum = sum + v end
	f.mean_nps_active = (#nz > 0) and (sum / #nz) or 0
	-- 90th percentile of non-zero measures: sorted[int(0.9 * (n-1))] (0-based)
	if #nz > 0 then
		local s = {}
		for i, v in ipairs(nz) do s[i] = v end
		table.sort(s)
		f.p90_nps_active = s[math.floor(0.9 * (#s - 1)) + 1]
	else
		f.p90_nps_active = 0
	end
	f.sust_nps_8 = Sustained(nps, 8)
	f.sust_nps_16 = Sustained(nps, 16)
	f.sust_nps_32 = Sustained(nps, 32)
	local r = math.max(rows, 1)
	f.log_rows = math.log(r)
	f.active_frac = #nz / math.max(#nps, 1)
	f.mines_per_row = radar.Mines / r
	f.holds_per_row = (radar.Holds + radar.Rolls) / r
	f.jumps_per_row = radar.Jumps / r
	f.hands_per_row = R("Hands") / r
	return f
end

-- steps: a Steps object. opts.any_type = true rates other steps types too
-- (the model was trained on dance-single only).
function DifficultyModel.Rating(steps, pn, opts)
	pn = pn or PLAYER_1
	if not (opts and opts.any_type) then
		if ToEnumShortString(steps:GetStepsType()) ~= "Dance_Single" then
			return nil, "not dance-single"
		end
	end
	local f, why = DifficultyModel.Features(steps, pn)
	if not f then return nil, why end
	local raw = B0
	for name, c in pairs(COEF) do
		local v = f[name]
		if v == nil or v ~= v or v == math.huge or v == -math.huge then
			return nil, "feature unavailable: " .. name
		end
		raw = raw + c * v
	end
	local cal = (#KX > 0) and Interp(raw, KX, KY) or raw
	local rating = math.floor(cal + 0.5)
	if rating < 1 then rating = 1 end
	if rating > MAX_RATING then rating = MAX_RATING end
	return rating, raw, cal
end
"""


def num(v):
    return repr(float(v))


def main():
    print("make_lua_rating.py: starting", flush=True)
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(1)
    src, dst = sys.argv[1], sys.argv[2]
    print("reading %s" % Path(src).resolve(), flush=True)
    m = json.load(open(src, encoding="utf-8-sig"))
    if m.get("version") != 2:
        sys.exit("model.json is not a v2 model (re-run fit_difficulty_model.py v2)")
    if m.get("tech_features", True):
        sys.exit("This model uses tech-count features; refit with --no-tech.")
    coef = {k: v for k, v in m["coefficients"].items() if v != 0.0}
    bad = [k for k in coef if k.startswith("tech_")]
    if bad:
        sys.exit("unsupported features: %s" % bad)
    cal = m.get("calibration_knots")
    kx = ", ".join(num(v) for v in cal["x"]) if cal else ""
    ky = ", ".join(num(v) for v in cal["y"]) if cal else ""
    cm = m.get("cv_metrics_calibrated") or m.get("cv_metrics_raw") or {}
    head = HEADER.format(steps_type=m["steps_type"], n=m["n_charts"],
                         mae="%.2f" % cm.get("MAE", float("nan")),
                         w1="%.1f" % cm.get("within1_%", float("nan")))
    body = BODY % {
        "b0": float(m["intercept"]),
        "coef": "".join("\t%s = %s,\n" % (k, num(v)) for k, v in coef.items()),
        "kx": kx, "ky": ky, "st": "StepsType_" + {
            "dance-single": "Dance_Single"}.get(m["steps_type"], m["steps_type"]),
    }
    Path(dst).write_text(head + body, encoding="utf-8")
    print("wrote %s: %d coefficients, %d calibration knots"
          % (Path(dst).resolve(), len(coef), len(cal["x"]) if cal else 0))


if __name__ == "__main__":
    try:
        main()
    except SystemExit:
        raise
    except Exception:
        import traceback
        traceback.print_exc()
        sys.exit(1)
